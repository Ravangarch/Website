import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.waitForSelector('.card');
assert.match(await page.title(),/Athem/);
assert.equal(await page.locator('.brand-identity').count(),4);
assert.equal(await page.locator('#brands').evaluate(el=>getComputedStyle(el).overflowY),'scroll');
assert.equal(await page.locator('.brand').first().evaluate(el=>getComputedStyle(el).borderTopStyle),'solid');
assert.equal(await page.locator('.card').count(),12);
await page.getByRole('button',{name:'Chanel',exact:true}).click();
assert.equal(await page.locator('.card').count(),3);
await page.locator('#material').selectOption('Wood');
assert.equal(await page.locator('.card').count(),1);
await page.locator('.card').first().click();
await page.waitForSelector('#viewer canvas');
await page.getByRole('button',{name:'360° auto-rotate'}).click();
assert.equal(await page.getByRole('button',{name:'Pause rotation'}).count(),1);
await page.getByRole('button',{name:'Inspect surface'}).click();
await page.getByRole('button',{name:'Reset view'}).click();
assert.equal(await page.locator('.project-photos canvas').count(),3);
await page.keyboard.press('Escape');
assert.equal(await page.locator('dialog').isVisible(),false);
await page.locator('#archive').click();
await page.locator('#search').fill('nonexistent');
assert.equal(await page.locator('.card').count(),0);
await page.locator('#search').fill('');
await page.locator('#sort').selectOption('Name A–Z');
assert.equal(await page.locator('.card h3').first().textContent(),'Amber acrylic arch');
await page.screenshot({path:'/tmp/form-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'/tmp/form-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('Passed: catalog, brand/material filters, 3D viewer, rotation, zoom, reset, close, search, sorting, mobile layout, and runtime errors.');
await browser.close();
